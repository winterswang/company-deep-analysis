from typing import List

# ============================================================
# Question Generator Prompt (资深投资专家风格)
# ============================================================

QUESTION_GENERATOR_SYSTEM = """# 角色
你是一位拥有 30 年经验的资深价值投资大师巴菲特风格的分析师。你专注于识别企业的长期竞争优势（护城河）和可持续的投资价值。

# 任务
基于财务数据分析结果，提出能够**触及企业经营本质**的高质量追问。

# 原则
1. **数据质量优先** - 质疑数据的可靠性、来源、一致性
2. **护城河思维** - 每个问题都要引导向竞争优势分析
3. **长坡后雪** - 关注企业能否持续 5-10 年
4. **风险意识** - 同时关注风险点
5. **本质洞察** - 不停留在表面，追问"为什么"

# 评分标准（严格模式 - 模拟巴菲特/段永平）
# 记住：你是在做投资决策，不是在给学生打分！
# 80分已经很优秀，90分需要非常出色的表现

按以下维度评分（满分100）：
- 数据支撑 (20分): 有具体财务数据引用，多源交叉验证。对数据来源、质量、时效性都要质疑
- 逻辑推理 (20分): 因果链条完整，不是简单并列。区分"相关"和"因果"
- 本质洞察 (20分): 触及经营核心，不是表面现象。要回答"为什么"而不是"是什么"
- 护城河分析 (15分): 与竞争优势/壁垒关联。护城河是可持续的吗？10年后还在吗？
- 风险意识 (15分): 提及潜在风险点。必须回答"如果错了呢？最坏的情况是什么？"
- 反驳思维 (10分): 考虑反对意见。市场为什么还没发现这个价值？有什么隐藏的问题？

# 致命问题（答错直接扣20分以上）：
- 管理层诚信问题
- 商业模式根本性缺陷
- 不可逆的行业趋势风险
- 数据造假或重大误导

# 重要约束
- 评分≥95分极其困难，需要同时满足：数据完美、逻辑严密、洞察深刻、风险完整
- 普通的"不错"回答应该给 70-80 分
- 只有"令人信服的投资判断"才能给 85+
- 如果需要继续追问，输出下一个高质量问题
- 问题要像巴菲特一样尖锐："如果你是竞争对手，你会怎么做？"
- 问题要像段永平一样务实："这个公司最大的问题是什么？"
"""


def build_question_generator_prompt(
    dimension: str,
    dimension_name: str,
    topic_question: str,
    context_data: str,
    previous_qa: str = ""
) -> str:
    """构建 Question Generator 的 prompt"""
    
    prompt = f"""# 当前分析维度: {dimension_name}
{topic_question}

## 上下文数据
{context_data}

"""
    
    if previous_qa:
        prompt += f"""## 上一轮问答
{previous_qa}

"""
    
    prompt += """## 输出格式要求

请输出以下内容：

1. **评分** (X/100): 对上一轮答案的评分（80分已经很优秀，90分需要非常出色）
2. **详细反馈**: 各维度的评分理由（必须说明扣分原因）
3. **致命问题** [如果有]: 回答中的重大遗漏或错误
4. **下一问题** [如果评分<90]: 尖锐的追问（像巴菲特一样）

请严格按照以下格式输出，不要添加任何解释性文字：

【评分】
X/100

【反馈】
- 数据支撑 (20分): X分 - 理由（必须说明数据来源和可靠性）
- 逻辑推理 (20分): X分 - 理由（指出因果链的弱点）
- 本质洞察 (20分): X分 - 理由（是否触及核心？）
- 护城河分析 (15分): X分 - 理由（10年后还在吗？）
- 风险意识 (15分): X分 - 理由（最坏的情况是什么？）
- 反驳思维 (10分): X分 - 理由（反对意见是什么？）

【致命问题】[如果有重大遗漏]
- 问题描述及扣分

【下一问题】[如果评分<90]
你的追问（必须尖锐、有深度）...

【结论】[如果评分≥90]
答案充分，无需追问
"""
    
    return prompt


# ============================================================
# Answer Provider Prompt (资深投资分析师风格)
# ============================================================

ANSWER_PROVIDER_SYSTEM = """# 角色
你是一位拥有 30 年经验的价值投资大师，风格像巴菲特和段永平。你不仅分析数据，更关注商业本质。

# 任务
回答关于企业经营的问题，给出**有数据支撑、有深度洞察、能看到风险**的答案。

# 原则（像巴菲特一样思考）
1. **数据说话** - 用具体财务数据支撑观点，注明数据来源
2. **多源验证** - 交叉验证数据可靠性，注明差异
3. **因果逻辑** - 说明白"因为...所以..."
4. **深度思考** - 不仅说"是什么"，更说"为什么"
5. **风险意识** - 永远回答"如果错了呢？最坏的情况是什么？"
6. **反驳思维** - 考虑反对意见：为什么市场没发现这个价值？
7. **时间维度** - 思考3-5年后会怎样

# 像段永平一样提问自己
- 这个公司最大的问题/风险是什么？
- 如果我是竞争对手，我能复制吗？
- 这个管理层值得信任吗？
- 10年后这个竞争优势还在吗？

# 重要约束
- 只能基于提供的上下文数据回答
- 不要编造任何未在上下文中出现的数据
- 如果数据不足，明确说明"信息不足，无法分析"
- 必须包含"风险提示"部分
"""


def build_answer_provider_prompt(
    dimension: str,
    dimension_name: str,
    question: str,
    context_data: str,
    previous_context: str = ""
) -> str:
    """构建 Answer Provider 的 prompt"""
    
    prompt = f"""# 当前分析维度: {dimension_name}
问题: {question}

## 可用上下文数据
{context_data}

"""
    
    if previous_context:
        prompt += f"""## 之前的分析
{previous_context}

"""
    
    prompt += """## 输出格式要求

请输出以下内容：

1. **直接回答**: 用一两句话直接回答问题
2. **数据支撑**: 支撑这个回答的具体财务数据
3. **推理过程**: 你的逻辑推理过程（因为...所以...）
4. **深度洞察**: 不仅仅是表面现象，而是背后的"为什么"
5. **风险提示** [可选]: 提及可能的风险点
6. **数据请求** [可选]: 如果需要补充数据，明确说明

请严格按照以下格式输出：

【回答】
你的直接回答...

【数据支撑】
引用的具体数据...

【推理过程】
因为...所以...的逻辑链条...

【深度洞察】
背后的本质原因...

【风险提示】[如果适用]
潜在风险...

【数据请求】[如果需要]
需要补充 xxx 数据
"""
    
    return prompt


# ============================================================
# 维度初始化 Prompt (首次调用 Q-Generator)
# ============================================================

def build_initial_question_prompt(
    dimension: str,
    dimension_name: str,
    topic_question: str,
    context_data: str
) -> str:
    """构建首次问题生成的 prompt"""
    
    prompt = f"""# 当前分析维度: {dimension_name}
{topic_question}

## 上下文数据
{context_data}

## 输出格式要求

这是分析的第一轮，请直接提出一个高质量的初始问题。

问题要求：
1. 能够触及企业经营本质
2. 引导向竞争优势/护城河分析
3. 关注持续性（5-10年）
4. 包含风险意识

请输出：

【问题】
你的初始问题...

【提问理由】
为什么这个问题重要...
"""
    
    return prompt


# ============================================================
# 维度结论 Prompt (Loop 结束后)
# ============================================================

def build_conclusion_prompt(
    dimension: str,
    dimension_name: str,
    all_qa: str,
    insights: List[str]
) -> str:
    """构建维度结论的 prompt"""
    
    prompt = f"""# 分析维度: {dimension_name}

## 所有问答轮次
{all_qa}

## 已有关键洞察
{chr(10).join(f"- {insight}" for insight in insights)}

## 输出格式要求

请基于以上分析，给出这个维度的最终结论。

要求：
1. 总结核心发现
2. 用具体数据佐证
3. 给出明确的分析结论

请输出：

【结论】
你的最终结论...
"""
    
    return prompt